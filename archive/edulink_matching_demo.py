def embed_search(query_text, topk=10):
    if not USE_EMBEDDINGS or emb_model is None:
        raise RuntimeError("Embedding model not available. Set USE_EMBEDDINGS=True in Colab with internet.")
    qv = emb_model.encode([query_text], normalize_embeddings=True)
