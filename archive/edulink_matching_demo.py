"""## 3. Method 1 – TF‑IDF / Keyword Matching

Build TF-IDF index on professor profiles
"""

tfidf = TfidfVectorizer(max_features=50000, ngram_range=(1,2), stop_words='english')
X_prof = tfidf.fit_transform(prof_df["profile_text"])

def tfidf_search(query_text, topk=10):
    qv = tfidf.transform([query_text])
    sims = cosine_similarity(qv, X_prof).ravel()
    top_idx = np.argsort(-sims)[:topk]
    results = prof_df.iloc[top_idx][["professor_name","author_id","topics_set","n_papers"]].copy()
    results["score"] = sims[top_idx]
    return results


