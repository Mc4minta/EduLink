"""## 5. Method 3 – Knowledge Graph Matching (Topic Overlap)"""

# Build lookup: author_id -> set(topics)
prof_topics = {row.author_id: set(row.topics_set) for _, row in prof_df.iterrows()}

def topic_overlap_score(q_topics, p_topics):
    if not q_topics or not p_topics:
        return 0.0
    inter = len(set(q_topics) & set(p_topics))
    uni = len(set(q_topics) | set(p_topics))
    return inter / uni  # Jaccard

def kg_search(query_topics, topk=10):
    scores = []
    for i, row in prof_df.iterrows():
        s = topic_overlap_score(query_topics, row.topics_set)
        scores.append(s)
    scores = np.array(scores)
    top_idx = np.argsort(-scores)[:topk]
    results = prof_df.iloc[top_idx][["professor_name","author_id","topics_set","n_papers"]].copy()
    results["score"] = scores[top_idx]
    return results


sample_topics = queries.iloc[0]["topics_list"]
kg_search(sample_topics, topk=5)

"""## 6. Method 4 – Hybrid Recall (TF‑IDF ∪ KG) + Optional Re‑Ranking"""

# Recall phase: take union of TF-IDF topN and KG topN -> candidate pool
# Re-rank phase: either weighted sum or cross-encoder reranker (if available)

def hybrid_candidates(query_text, query_topics, tfidf_k=100, kg_k=100):
    tfidf_res = tfidf_search(query_text, topk=tfidf_k)
    kg_res = kg_search(query_topics, topk=kg_k)
    cand_ids = set(tfidf_res["author_id"]).union(set(kg_res["author_id"]))
    cand_df = prof_df[prof_df["author_id"].isin(cand_ids)].copy()
    # Pre-compute base scores for weighted fusion
    tfidf_full = tfidf.transform([query_text]).toarray().ravel()
    prof_mat = X_prof.toarray()
    tfidf_scores = cosine_similarity([tfidf_full], prof_mat).ravel()
    topic_scores = np.array([topic_overlap_score(query_topics, row.topics_set) for _, row in prof_df.iterrows()])
    cand_df["tfidf_score"] = tfidf_scores[prof_df["author_id"].isin(cand_ids)]
    cand_df["kg_score"] = topic_scores[prof_df["author_id"].isin(cand_ids)]
    return cand_df

# cross-encoder reranker
USE_RERANKER = False  # if  sentence-transformers

if USE_RERANKER:
    try:
        from sentence_transformers.cross_encoder import CrossEncoder
        rerank_model_name = "BAAI/bge-reranker-large"
        reranker = CrossEncoder(rerank_model_name)
    except Exception as e:
        print("Reranker setup failed:", e)
        USE_RERANKER = False

def hybrid_search(query_text, query_topics, topk=10, w_tfidf=0.6, w_kg=0.4):
    cands = hybrid_candidates(query_text, query_topics, tfidf_k=150, kg_k=150)

    if USE_RERANKER:
        # Build pairs: (query_text, professor_profile_text)
        pairs = [(query_text, txt) for txt in cands["profile_text"].tolist()]
        scores = reranker.predict(pairs)  # higher is better
        cands["rerank_score"] = scores
        cands["final_score"] = cands["rerank_score"]
    else:
        # Weighted late-fusion
        cands["final_score"] = w_tfidf * cands["tfidf_score"].fillna(0) + w_kg * cands["kg_score"].fillna(0)

    cands = cands.sort_values("final_score", ascending=False).head(topk)
    return cands[["professor_name","author_id","topics_set","n_papers","final_score"]]

"""## 7. Unified Query Helper"""

def query_professors(project_title:str, project_desc:str, project_topics:list, method:str="tfidf", topk:int=10):
    query_text = f"{project_title} {project_desc} " + " ".join(project_topics or [])
    method = method.lower()
    if method == "tfidf":
        return tfidf_search(query_text, topk=topk)
    elif method == "embed":
        return embed_search(query_text, topk=topk)
    elif method == "kg":
        return kg_search(project_topics or [], topk=topk)
    elif method == "hybrid":
        return hybrid_search(query_text, project_topics or [], topk=topk)
    else:
        raise ValueError("method must be one of: tfidf | embed | kg | hybrid")

