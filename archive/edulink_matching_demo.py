"""## 8. Evaluation (Automatic, Weak-Label)"""

# treat each paper as a query; the correct professor is the paper's author.
# Metric: Recall@K (K in {1,3,5,10}). evaluate for TF-IDF, KG, Hybrid.
# Embeddings + Reranker can be enabled by toggling flags

def recall_at_k(ranked_author_ids, gold_author_id, K):
    return 1.0 if gold_author_id in ranked_author_ids[:K] else 0.0

def evaluate(method="tfidf", n_samples=200, Ks=(1,3,5,10)):
    sample = queries.sample(min(n_samples, len(queries)), random_state=SEED)
    recalls = {K: [] for K in Ks}

    for _, row in tqdm(sample.iterrows(), total=len(sample)):
        qtext = row["query_text"]
        qtopics = row["topics_list"]
        gold = row["author_id"]
        if method == "tfidf":
            res = tfidf_search(qtext, topk=max(Ks))
        elif method == "kg":
            res = kg_search(qtopics or [], topk=max(Ks))
        elif method == "hybrid":
            res = hybrid_search(qtext, qtopics or [], topk=max(Ks))
        elif method == "embed":
            if not USE_EMBEDDINGS:
                continue
            res = embed_search(qtext, topk=max(Ks))
        else:
            raise ValueError(method)

        ranked = res["author_id"].tolist()
        for K in Ks:
            recalls[K].append(recall_at_k(ranked, gold, K))

    out = {f"Recall@{K}": float(np.mean(recalls[K])) if recalls[K] else None for K in Ks}
    return out

