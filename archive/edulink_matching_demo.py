# Aggregate per professor (merge multiple papers into one profile)
def build_prof_profiles(df):
    profs = []
    for name, g in df.groupby(["professor_name", "author_id"]):
        texts = g["base_text"].tolist()
        titles = g["work_title"].dropna().tolist()
        topics = [t for xs in g["topics_list"].tolist() for t in xs]
        profs.append({
            "professor_name": name[0],
            "author_id": name[1],
            "n_papers": len(g),
            "titles_recent": titles[:5],
            "topics_set": sorted(list(set(topics))),
            "profile_text": " ".join(texts)
        })
    return pd.DataFrame(profs)

